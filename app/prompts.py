from app.models import ResearchRequest


def build_research_query(request: ResearchRequest) -> str:
    profile = request.candidate_profile or "候选人暂未提供个人背景，只分析通用能力要求"
    focus = request.focus or "无额外要求"
    return f"""
你是一名严谨的中国招聘市场研究员。请调研“{request.city}地区、{request.seniority}级别的{request.role}”岗位。

候选人背景：
{profile}

额外关注：
{focus}

只使用能够核验的公开信息，优先使用近期招聘页面、公司官方招聘页面、权威行业报告和主流招聘平台。
最终必须生成中文 Markdown 报告，并严格包含以下部分：

1. 执行摘要：用不超过200字概括市场需求与候选人匹配情况。
2. 岗位画像：典型职责、工作场景，以及初级/中级/高级岗位边界。
3. 技能矩阵：以表格列出技能、重要程度、证据、候选人现状和差距；区分“招聘信息明确要求”和“你的推断”。
4. 市场需求证据：总结高频要求、常见技术栈及行业分布；不要在证据不足时编造精确比例。
5. 候选人差距分析：分为已有优势、关键缺口、可暂缓能力。未提供候选人信息时明确说明无法判断。
6. 8周行动计划：每周给出学习目标、可交付成果和验收标准。
7. 简历项目建议：给出1个能证明核心能力的项目，列出功能、技术栈、量化指标和面试讲解点。
8. 风险与局限：说明样本偏差、信息时效和无法确认的内容。
9. 引用来源：每项关键结论使用可点击链接引用，禁止虚构URL。

不要输出空泛的求职鼓励，不要把搜索结果数量冒充市场占比。
""".strip()

